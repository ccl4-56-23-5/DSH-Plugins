const fs=require('node:fs'),path=require('node:path'),{pathToFileURL}=require('node:url'),{registerHooks}=require('node:module'),assert=require('node:assert/strict');
(async()=>{
  const root=path.resolve(__dirname,'..'),base='D:/DeepSeekHarness/resources/app.asar/dsh/node_modules/@deepseek-ai/';
  registerHooks({resolve(specifier,context,next){
    if(specifier==='@deepseek-ai/dsh-tools')return {url:pathToFileURL(base+'dsh-tools/lib/index.js').href,shortCircuit:true};
    return next(specifier,context);
  }});
  const {Context}=await import(pathToFileURL(base+'cordis/lib/index.js').href);
  const tools=await import(pathToFileURL(base+'dsh-tools/lib/index.js').href);
  const system=await import(pathToFileURL(base+'dsh-system-prompt/lib/index.js').href);
  const suite=await import(pathToFileURL(root+'/lib/index.js').href);
  const {WorldbookStore}=await import(pathToFileURL(root+'/lib/core.js').href);
  const {exampleBook}=await import(pathToFileURL(root+'/lib/example.js').href);
  const home=path.resolve(process.argv[2]);fs.mkdirSync(home,{recursive:true});process.env.DSH_HOME=home;
  const store=new WorldbookStore(path.join(home,'storydeck/worldbook-v1.json'));
  const action=(kind,args)=>store.author(kind,{requestId:crypto.randomUUID(),revision:store.read().revision,...args});
  action('saveBook',{book:exampleBook});action('createStory',{id:'host-test',title:'隔离宿主验证',bookId:exampleBook.id});action('bind',{sessionId:'host-test-session',storyId:'host-test'});
  const ctx=new Context();
  ctx.plugin(tools.default);ctx.plugin(system.default);const parent=ctx.plugin(suite);
  for(let i=0;i<30;i++)await new Promise(resolve=>setImmediate(resolve));
  assert.ok(ctx.tools,'ToolRuntime did not load');assert.ok(ctx.systemPrompt,'SystemPrompt did not load');
  const read=ctx.tools.get('storydeck_context'),commit=ctx.tools.get('storydeck_commit');
  assert.ok(read&&commit,'Worldbook child tools did not load');
  const agent={session:{id:'host-test-session'}},exec={agent,signal:AbortSignal.timeout(5000)};
  const before=JSON.parse(await read.execute({query:'御剑',limit:8},exec));
  assert.equal(before.state.realm,'炼气');
  const changed=JSON.parse(await commit.execute({requestId:crypto.randomUUID(),revision:before.revision,eventJson:JSON.stringify({expectedStateRevision:before.stateRevision,certainty:'confirmed',summary:'突破并学会御剑术',source:'主角已筑基成功，并跟随师父学会了御剑术。',patch:{realm:'筑基',skills:['御剑术']}})},exec));
  assert.equal(changed.state.realm,'筑基');
  const after=JSON.parse(await read.execute({query:'御剑',limit:8},exec));
  assert.ok(after.entries.some(e=>e.id==='flight'));
  assert.ok(!after.entries.some(e=>['secret','golden-core'].includes(e.id)));
  await assert.rejects(()=>read.execute({query:'',limit:8},{...exec,agent:{session:{id:'unbound'}}}),/未关联/);
  const assembly=await ctx.systemPrompt.assemble({scope:agent});
  assert.ok(assembly.sections.some(s=>s.name==='storydeck:worldbook-policy'));
  assert.ok(assembly.contexts.some(s=>s.name==='storydeck:current-state'&&s.text.includes('筑基')));
  const empty=await ctx.systemPrompt.assemble({scope:{session:{id:'unbound'}}});
  assert.ok(!empty.sections.some(s=>s.name==='storydeck:worldbook-policy'&&s.text));
  await parent.dispose();
  assert.equal(ctx.tools.get('storydeck_context'),undefined);
  const result={ok:true,node:process.version,checks:['real installed Cordis parent mounts child','real defineTool validates and executes read/commit','automatic event changes eligible records','hidden and wrong-realm entries excluded','unbound session rejected','prompt and dynamic state scoped to current session','parent disposal removes tools'],boundary:'isolated installed host runtime; no live model request or desktop install'};
  fs.writeFileSync(path.join(home,'host-result.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result,null,2));
})().catch(e=>{console.error(e);process.exitCode=1;});
